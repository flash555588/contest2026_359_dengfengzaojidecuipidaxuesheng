#!/usr/bin/env python3
"""Author compact file-type materials as shared LVGL RGB565+A8 images.

No runtime SVG decoding, image worker or per-card pixel allocation is required.
"""
from pathlib import Path
import argparse,math,struct,zlib
W=H=32
KINDS={'image':(83,163,146),'video':(135,123,202),'audio':(217,123,156),
       'text':(146,161,179),'pdf':(221,110,101),'document':(100,157,210),
       'spreadsheet':(100,168,126),'presentation':(220,155,93),
       'archive':(192,156,94),'package':(155,126,196),'code':(111,139,172),
       'font':(102,164,173),'generic':(168,175,187)}
def rounded(x,y,l,t,r,b,rad):
 if not(l<=x<r and t<=y<b):return False
 cx=max(l+rad,min(r-rad,x));cy=max(t+rad,min(b-rad,y))
 return (x-cx)**2+(y-cy)**2<=rad*rad

def polygon(x,y,points):
 hit=False;j=len(points)-1
 for i,(px,py) in enumerate(points):
  qx,qy=points[j]
  if (py>y)!=(qy>y) and x<(qx-px)*(y-py)/(qy-py)+px:hit=not hit
  j=i
 return hit

def stroke(x,y,points,width=1.6):
 for (a,b),(c,d) in zip(points,points[1:]):
  dx,dy=c-a,d-b;v=dx*dx+dy*dy
  t=max(0,min(1,((x-a)*dx+(y-b)*dy)/v)) if v else 0
  if (x-a-t*dx)**2+(y-b-t*dy)**2<=(width/2)**2:return True
 return False

def circle(x,y,cx,cy,r):return (x-cx)**2+(y-cy)**2<=r*r
FONT={'P':['111','101','111','100','100'],'D':['110','101','101','101','110'],
      'F':['111','100','110','100','100'],'A':['010','101','111','101','101'],
      'a':['000','110','011','101','111']}
def letters(x,y,text,left,top,scale):
 for i,ch in enumerate(text):
  px=int((x-left-i*4*scale)/scale);py=int((y-top)/scale)
  if x>=left+i*4*scale and y>=top and 0<=px<3 and 0<=py<5 and FONT[ch][py][px]=='1':return True
 return False

def glyph(kind,x,y):
 if kind=='video':return polygon(x,y,[(13,10),(23,16),(13,22)])
 if kind=='image':return circle(x,y,23,10,2.2) or polygon(x,y,[(3,25),(12,15),(18,21),(22,17),(30,25)])
 if kind=='audio':return stroke(x,y,[(13,22),(13,11),(23,9),(23,20)],1.8) or stroke(x,y,[(13,14),(23,12)],1.5) or circle(x,y,10.8,22.5,2.8) or circle(x,y,20.8,20.5,2.8)
 if kind=='text' or kind=='document':return any(stroke(x,y,[(10,yy),(22 if yy!=23 else 18,yy)],1.5) for yy in (13,18,23))
 if kind=='pdf':return letters(x,y,'PDF',9,17,1.2)
 if kind=='spreadsheet':return any(stroke(x,y,p,1.1) for p in [[(9,12),(23,12),(23,25),(9,25),(9,12)],[(9,16),(23,16)],[(9,20.5),(23,20.5)],[(14,12),(14,25)],[(18.5,12),(18.5,25)]])
 if kind=='presentation':return stroke(x,y,[(9,12),(23,12),(23,22),(9,22),(9,12)],1.4) or stroke(x,y,[(16,22),(16,26),(12,26),(20,26)],1.4) or polygon(x,y,[(14,15),(19,17),(14,19)])
 if kind=='archive':return any(rounded(x,y,14+(i%2)*2,6+i*2,16+(i%2)*2,8+i*2,.4) for i in range(8)) or stroke(x,y,[(14,22),(18,22),(18,27),(14,27),(14,22)],1.5)
 if kind=='package':return any(stroke(x,y,p,1.5) for p in [[(8,13),(16,9),(24,13),(24,22),(16,27),(8,22),(8,13),(16,17),(24,13)],[(16,17),(16,27)],[(12,11),(20,15)]])
 if kind=='code':return any(stroke(x,y,p,1.6) for p in [[(12,13),(8,18),(12,23)],[(21,13),(25,18),(21,23)],[(18,12),(15,24)]])
 if kind=='font':return letters(x,y,'Aa',8,15,2)
 return False

def sample(kind,x,y):
 color=KINDS[kind];p=(0,0,0,0)
 wide=kind in ('image','video')
 if rounded(x,y,1 if wide else 4,5 if wide else 2,31 if wide else 28,30 if wide else 32,3):p=(51,56,65,22)
 body=rounded(x,y,0 if wide else 4,3 if wide else 1,32 if wide else 28,29 if wide else 31,3)
 cut=not wide and polygon(x,y,[(20,0),(29,0),(29,9)])
 if body and not cut:
  t=y/32;p=tuple(round(c+(255-c)*.13*(1-t)-c*.05*t) for c in color)+(255,)
 if not wide and polygon(x,y,[(20,1),(20,9),(28,9)]):p=tuple(round(c+(255-c)*.45) for c in color)+(255,)
 if p[3]==255 and glyph(kind,x,y):p=(255,255,255,235)
 return p

def pixels(kind):
 out=[]
 for y in range(H):
  for x in range(W):
   samples=[sample(kind,x+(sx+.5)/4,y+(sy+.5)/4) for sy in range(4) for sx in range(4)]
   alpha=sum(p[3] for p in samples)
   rgb=[round(sum(p[c]*p[3] for p in samples)/alpha) if alpha else 0 for c in range(3)]
   out.append((*rgb,round(alpha/16)))
 return out

def png(path,pix,w,h):
 def chunk(kind,data):return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data)&0xffffffff)
 raw=b''.join(b'\0'+bytes(c for px in pix[y*w:(y+1)*w] for c in px) for y in range(h))
 path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',w,h,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b''))

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--preview-dir',type=Path);a=p.parse_args()
 if a.preview_dir:a.preview_dir.mkdir(parents=True,exist_ok=True)
 lines=['/* SPDX-License-Identifier: Apache-2.0 */','/* Generated by tools/generate_file_icons.py; shared immutable image materials. */','#include "glass_file_types.h"']
 for kind in KINDS:
  pix=pixels(kind)
  data=b''.join(struct.pack('<H',((r>>3)<<11)|((g>>2)<<5)|(b>>3)) for r,g,b,alpha in pix)+bytes(p[3] for p in pix)
  lines.append('static const unsigned char files_%s_pixels[] = {'%kind)
  lines.extend('  '+','.join('0x%02x'%v for v in data[i:i+24])+',' for i in range(0,len(data),24))
  lines.extend(['};','static const lv_image_dsc_t files_%s_image = {'%kind,'  .header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,.w=32,.h=32,.stride=64},','  .data_size=sizeof(files_%s_pixels),.data=files_%s_pixels'%(kind,kind),'};'])
  if a.preview_dir:png(a.preview_dir/(kind+'.png'),pix,W,H)
 lines.append('static const lv_image_dsc_t *const files_type_images[] = { '+', '.join('&files_'+k+'_image' for k in KINDS)+' };\n')
 root=Path(__file__).resolve().parents[1]
 (root/'app/espdl-quickapp/overlay/apps/system/desktop/glass_file_icons.inc').write_bytes(('\n'.join(lines)).encode())
 print('%d shared file icons; %d pixel bytes in flash, one image per file tile'%(len(KINDS),len(KINDS)*W*H*3))
if __name__=='__main__':main()
