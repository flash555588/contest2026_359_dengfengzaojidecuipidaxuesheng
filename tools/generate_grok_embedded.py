#!/usr/bin/env python3
"""Generate the host-only renderer snapshot; firmware uses SD frames."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1];base=root/'ouo';desktop=root/'app/espdl-quickapp/overlay/apps/system/desktop'
adapter=(base/'grok_lvgl_adapter.js').read_text(encoding='utf-8')
adapter=adapter.replace('var registry = {}','var pixelBody=4,pixelDetail=2;\n  var registry = {}',1)
adapter=adapter.replace('mount:function(width,height) {','mount:function(width,height,diameter,centerX,centerY,bodyCell,detailCell,homeStyle) {pixelBody=bodyCell;pixelDetail=detailCell;',1)
adapter=adapter.replace('scale=Math.min(height*0.56/228,width/420);originX=width/2-114.2705*scale;originY=height*0.43-114.2705*scale;', 'scale=diameter/228;originX=centerX-114.2705*scale;originY=centerY-114.2705*scale;')
assert 'originX=centerX-' in adapter
adapter=adapter.replace('var grad=gradient(fill,m,points,packed);','var grad=gradient(fill,m,points,packed);\n        var pixelCell=grad&&grad[0]===1?pixelBody:pixelDetail;')
for call in ['ui.polygonBuffer(points.buffer,c,opa,width,grad)','ui.polygon(points,c,opa,width,grad)','ui.polygonSetBuffer(n.handles[k],points.buffer,c,opa,width,grad)','ui.polygonSet(n.handles[k],points,c,opa,width,grad)']:
    assert adapter.count(call)==1;adapter=adapter.replace(call,call[:-1]+',pixelCell)')
license=(base/'vendor/GROK-BALL-LICENSE.txt').read_text(encoding='utf-8')
engine=(base/'vendor/grok-ball.js').read_text(encoding='utf-8')
driver=(base/'grok_embedded.js').read_text(encoding='utf-8')
prelude='/* SPDX-License-Identifier: Apache-2.0 AND MIT\n'+license+'\n*/\n'+adapter
source=prelude+'\n'+engine+'\n'+driver
(base/'embedded.js').write_text(source,encoding='utf-8')
# Reuse the immutable engine already present in the standalone OuO resource.
# Keep the complete JS above for tooling; native VMs evaluate three shared
# source spans in dependency order, without adding a duplicate SDK to flash.
offline=root/'tools/grok_offline';sdk=engine.encode('utf-8')
rows=(offline/'ouo_resource.c').read_text(encoding='utf-8').splitlines()
app=''.join(json.loads(row.rstrip(';')) for row in rows if row.startswith('"')).encode('utf-8')
assert app.count(sdk)==1,'Regenerate the pinned OuO package first'
offset=app.index(sdk)
rows=(offline/'ouo_resource.c').read_text(encoding='utf-8').splitlines()
decoded=''.join(json.loads(row.rstrip(';')) for row in rows if row.startswith('"')).encode('utf-8')
assert decoded==app,'OuO C resource is stale'
def declaration(name,text):
    return 'const char '+name+'[] =\n'+'\n'.join(json.dumps(line,ensure_ascii=False) for line in text.splitlines(keepends=True))+';\nconst unsigned '+name+'_size=sizeof('+name+')-1;\n'
resource='/* Generated by generate_grok_embedded.py. SPDX-License-Identifier: Apache-2.0 AND MIT */\n'
resource+=declaration('glass_grok_js',prelude)+declaration('glass_grok_driver_js',driver)
resource+=f'const unsigned glass_grok_engine_offset={offset};\nconst unsigned glass_grok_engine_size={len(sdk)};\n'
(offline/'glass_grok_resource.c').write_text(resource,encoding='utf-8');print('GROK_OFFLINE_RESOURCE_OK',len(source.encode('utf-8')),'JS bytes;',len(sdk),'host-only engine bytes')
