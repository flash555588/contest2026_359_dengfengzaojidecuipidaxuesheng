#!/usr/bin/env python3
"""Crop original generated sky artwork to native sizes and baseline JPEG.

Requires Pillow. Original PNGs and generation provenance accompany the JPEGs.
The firmware reuses its existing tiny JPEG decoder, with no SD/network I/O.
"""
from pathlib import Path
from PIL import Image, ImageOps
import hashlib
import json


def main():
    repo=Path(__file__).resolve().parents[1]
    assets=repo/'app/espdl-quickapp/assets/weather'
    out=repo/'app/espdl-quickapp/overlay/apps/system/desktop/glass_weather_art.inc'
    lines=['/* SPDX-License-Identifier: Apache-2.0 */',
           '/* Generated by tools/prepare_weather_art.py. Original artwork provenance:',
           ' * app/espdl-quickapp/assets/weather/SOURCES.md */',
           'struct weather_art {const uint8_t *data; size_t size; unsigned w,h;};']
    records=[]
    names=['clear','cloudy','overcast','clear-night','cloudy-night',
           'rain','rain-heavy','thunder','snow','snow-heavy','sleet','fog','haze','dust',
           'drizzle','rain-moderate','rain-large','rain-extreme','showers','hail',
           'freezing-rain','snow-moderate','snow-large','snow-showers',
           'dust-floating','dust-blowing','wind','thunder-hail','tornado','tropical-storm']
    for compact,(width,height) in [(0,(588,326)),(1,(307,272))]:
        for index,name in enumerate(names):
            image=Image.open(assets/f'{name}-original.png').convert('RGB')
            image=ImageOps.fit(image,(width,height),Image.Resampling.LANCZOS,
                              centering=(0.78,0.3))
            path=assets/f'{name}-{"card" if compact else "detail"}.jpg'
            image.save(path,'JPEG',quality=84,optimize=True,progressive=False,subsampling=0)
            data=path.read_bytes()
            symbol=f'weather_art_{compact}_{index}'
            rows='\n'.join('  '+','.join(f'0x{n:02x}' for n in data[i:i+24])+',' for i in range(0,len(data),24))
            lines.append(f'static const uint8_t {symbol}[] = {{\n{rows}\n}};')
            records.append({'file':path.name,'bytes':len(data),'width':width,'height':height,
                            'raw_rgb565_bytes':width*height*2,'sha256':hashlib.sha256(data).hexdigest()})
    enums=['WEATHER_ART_'+name.upper().replace('-','_') for name in names]
    lines.append('enum weather_art_index { '+', '.join(enums+['WEATHER_ART_NONE'])+' };')
    lines.append('static const struct weather_art weather_artworks[2][WEATHER_ART_NONE] = {')
    for compact,(width,height) in [(0,(588,326)),(1,(307,272))]:
        lines.append('  {'+','.join(f'{{weather_art_{compact}_{i},sizeof(weather_art_{compact}_{i}),{width},{height}}}' for i in range(len(names)))+'},')
    lines.append('};\n')
    out.write_text('\n'.join(lines),encoding='utf-8')
    result={'assets':records,'total_flash_bytes':sum(r['bytes'] for r in records),
            'source_bytes':sum((assets/f'{n}-original.png').stat().st_size for n in names)}
    (assets/'compression.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,indent=2))


if __name__=='__main__':main()
