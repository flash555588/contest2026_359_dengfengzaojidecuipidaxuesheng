#!/usr/bin/env python3
"""Embed the three reviewable runtime agent.md defaults without filesystem I/O."""
from pathlib import Path
import json

desktop = Path(__file__).resolve().parents[1] / 'app/espdl-quickapp/overlay/apps/system/desktop'
text = '/* Generated by tools/generate_agent_profiles.py; do not edit. */\n'
for mode in ('chat', 'create', 'assistant'):
    profile = (desktop / 'agents' / mode / 'agent.md').read_text(encoding='utf-8')
    text += f'static const char agent_profile_{mode}[] = {json.dumps(profile, ensure_ascii=False)};\n'
(desktop / 'glass_agent_profiles.h').write_bytes(text.encode('utf-8'))
