#!/usr/bin/env python3
"""Exercise the real skill/config/RPC code with bounded mock HTTP peers."""
from pathlib import Path
import argparse, subprocess, os, json
p=argparse.ArgumentParser();p.add_argument('--apps',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
repo=Path(__file__).resolve().parents[1];desktop=repo/'app/espdl-quickapp/overlay/apps/system/desktop'
expected='/* Generated by tools/generate_agent_profiles.py; do not edit. */\n'
for mode in ('chat','create','assistant'):
    expected+='static const char agent_profile_'+mode+'[] = '+json.dumps((desktop/'agents'/mode/'agent.md').read_text(encoding='utf-8'),ensure_ascii=False)+';\n'
assert (desktop/'glass_agent_profiles.h').read_text(encoding='utf-8')==expected,'Run tools/generate_agent_profiles.py after editing agent.md'
a.output.mkdir(parents=True,exist_ok=True);(a.output/'nuttx').mkdir(exist_ok=True);(a.output/'nuttx/config.h').write_text('#pragma once\n')
skills=a.output/'skills';skills.mkdir(exist_ok=True)
profiles=a.output/'profiles';profiles.mkdir(exist_ok=True)
cjson=a.apps/'netutils/cjson/cJSON'
flags=['-std=gnu11','-O1','-g','-D_GNU_SOURCE','-fsanitize=address,undefined','-fno-omit-frame-pointer','-ffunction-sections','-fdata-sections','-pthread','-I'+str(a.output),'-I'+str(desktop),'-I'+str(cjson)]
flags+=['-DAGENT_PROFILE_ROOT="'+str(profiles)+'"']
env={**os.environ,'ASAN_OPTIONS':'detect_leaks=1','UBSAN_OPTIONS':'halt_on_error=1'}
sources=[repo/'app/espdl-quickapp/tests/agent_host.c',desktop/'glass_agent.c',desktop/'glass_agent_config.c',desktop/'glass_portal_config.c',desktop/'glass_chat_store.c',cjson/'cJSON.c']
subprocess.run(['gcc',*flags,'-DAGENT_SKILL_ROOT="'+str(skills)+'"',*map(str,sources),'-Wl,--gc-sections','-o',str(a.output/'agent-host')],check=True)
subprocess.run([str(a.output/'agent-host'),str(skills)],check=True,env=env)
(a.output/'netutils').mkdir(exist_ok=True)
(a.output/'netutils/webclient.h').write_text('''#pragma once
#include <stdbool.h>
#include <stddef.h>
#define WEBCLIENT_PROTOCOL_VERSION_HTTP_1_1 1
struct webclient_tls_ops {int unused;};
struct webclient_tls_connection;
struct webclient_context {
 const char *url,*method; const char *const *headers; unsigned nheaders,protocol_version,timeout_sec,http_status;
 char *buffer;size_t buflen;const struct webclient_tls_ops *tls_ops;void *tls_ctx;
 int (*sink_callback)(char **,int,int,int *,void *);void *sink_callback_arg;
 int (*header_callback)(const char *,bool,void *);void *header_callback_arg;
};
void webclient_set_defaults(struct webclient_context *);
void webclient_set_static_body(struct webclient_context *,const char *,size_t);
int webclient_perform(struct webclient_context *);
''')
subprocess.run(['gcc',*flags,str(repo/'app/espdl-quickapp/tests/mcp_http_host.c'),str(desktop/'glass_agent_config.c'),str(cjson/'cJSON.c'),'-o',str(a.output/'mcp-http-host')],check=True)
subprocess.run([str(a.output/'mcp-http-host')],check=True,env=env)
bridge_flags=flags+['-I'+str(repo/'app/espdl-quickapp/overlay/apps/system/espclaw/include'),'-I'+str(a.apps/'system/espclaw/include'),'-I'+str(desktop/'espdl_port/include')]
subprocess.run(['gcc',*bridge_flags,str(repo/'app/espdl-quickapp/tests/agent_bridge_host.c'),str(desktop/'glass_agent.c'),str(desktop/'glass_agent_config.c'),str(desktop/'glass_chat_store.c'),str(cjson/'cJSON.c'),'-Wl,--gc-sections','-o',str(a.output/'agent-bridge-host')],check=True)
subprocess.run([str(a.output/'agent-bridge-host')],check=True,env=env)

mode_flags=bridge_flags+['-DCHAT_DATA_ROOT="'+str(a.output/'chat-data')+'"']
subprocess.run(['gcc',*mode_flags,str(repo/'app/espdl-quickapp/tests/agent_modes_host.c'),str(desktop/'glass_chat_service.c'),str(desktop/'glass_chat_store.c'),str(cjson/'cJSON.c'),'-Wl,--gc-sections','-o',str(a.output/'agent-modes-host')],check=True)
subprocess.run([str(a.output/'agent-modes-host')],check=True,env=env)
subprocess.run(['gcc',*flags,str(repo/'app/espdl-quickapp/tests/chat_markup_host.c'),'-o',str(a.output/'chat-markup-host')],check=True)
subprocess.run([str(a.output/'chat-markup-host')],check=True,env=env)
