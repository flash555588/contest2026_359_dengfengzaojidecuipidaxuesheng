#!/usr/bin/env python3
"""Generate an 8-row ordered-dither RGB565 fill for the LVGL music card.

Small tiled fills remove coarse RGB565 gradient bands. This contains no UI
text, artwork or controls; all foreground elements remain native LVGL objects.
"""
from pathlib import Path

BAYER = [[0,48,12,60,3,51,15,63],[32,16,44,28,35,19,47,31],
         [8,56,4,52,11,59,7,55],[40,24,36,20,43,27,39,23],
         [2,50,14,62,1,49,13,61],[34,18,46,30,33,17,45,29],
         [10,58,6,54,9,57,5,53],[42,26,38,22,41,25,37,21]]


def main():
    out=Path(__file__).resolve().parents[1]/'app/espdl-quickapp/overlay/apps/system/desktop/glass_home_gradient.inc'
    width=567;height=8
    text=['/* SPDX-License-Identifier: Apache-2.0 */',
          '/* Generated by tools/generate_home_gradient.py: RGB565 dither tile. */']
    start=(0x27,0x25,0x34)
    for palette,end in enumerate([(0x69,0x50,0x70),(0x75,0x4f,0x48),(0x45,0x6e,0x67)]):
        values=[]
        for y in range(height):
            for x in range(width):
                quant=[]
                for channel,bits in enumerate([5,6,5]):
                    c=start[channel]+(end[channel]-start[channel])*x/(width-1)
                    exact=c*((1<<bits)-1)/255
                    threshold=(BAYER[y][x%8]+.5)/64
                    lower=int(exact)
                    quant.append(min((1<<bits)-1,lower+(exact-lower>threshold)))
                pixel=quant[0]<<11|quant[1]<<5|quant[2]
                values.extend([pixel&255,pixel>>8])
        rows='\n'.join('  '+','.join(f'0x{n:02x}' for n in values[i:i+24])+',' for i in range(0,len(values),24))
        text.append(f'''static const uint8_t home_gradient_pixels_{palette}[] = {{
{rows}
}};
static const lv_image_dsc_t home_gradient_{palette} = {{
  .header.magic = LV_IMAGE_HEADER_MAGIC, .header.cf = LV_COLOR_FORMAT_RGB565,
  .header.w = {width}, .header.h = {height}, .header.stride = {width*2},
  .data_size = sizeof(home_gradient_pixels_{palette}), .data = home_gradient_pixels_{palette}
}};''')
    text.append('static const lv_image_dsc_t *const home_gradients[] = {&home_gradient_0, &home_gradient_1, &home_gradient_2};\n')
    out.write_text('\n'.join(text),encoding='utf-8');print('Generated music gradient fills: 27,216 bytes')


if __name__=='__main__':main()
