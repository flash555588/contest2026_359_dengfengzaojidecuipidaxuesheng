#!/usr/bin/env python3
"""Build pinned static lyric fonts, catalog and an SD install archive.

Requires fontTools 4.60.1. No device access or firmware/configuration writes.
Copy the archive's fonts directory into /sdcard; keep existing fonts alongside it.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import urllib.request
import zipfile
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

FACES = [
    ('思源黑体', 'Sans', 'notosanssc/NotoSansSC[wght].ttf'),
    ('思源宋体', 'Serif', 'notoserifsc/NotoSerifSC[wght].ttf'),
    ('马善政楷书', 'Brush', 'mashanzheng/MaShanZheng-Regular.ttf'),
    ('站酷快乐体', 'Happy', 'zcoolkuaile/ZCOOLKuaiLe-Regular.ttf'),
    ('站酷黄油体', 'Butter', 'zcoolqingkehuangyou/ZCOOLQingKeHuangYou-Regular.ttf'),
    ('站酷小薇体', 'XiaoWei', 'zcoolxiaowei/ZCOOLXiaoWei-Regular.ttf'),
]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--header', type=Path, required=True)
    parser.add_argument('--fetch', action='store_true')
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[1]
    lock = json.loads((repo/'app/espdl-quickapp/assets/lyric-fonts.lock.json').read_text(encoding='utf-8'))
    root = args.output/'sdcard/fonts/lyrics'
    root.mkdir(parents=True, exist_ok=True)
    records = []
    for name, key, relative in FACES:
        paths = [relative, relative.split('/')[0]+'/OFL.txt']
        for path in paths:
            target = args.cache/path
            record = lock['files'][path]
            if not target.exists() and args.fetch:
                target.parent.mkdir(parents=True, exist_ok=True)
                with urllib.request.urlopen(record['url'], timeout=90) as response:
                    data = response.read(32*1024*1024)
                assert hashlib.sha256(data).hexdigest() == record['sha256'], path
                target.write_bytes(data)
            assert target.stat().st_size == record['bytes'], path
            assert hashlib.sha256(target.read_bytes()).hexdigest() == record['sha256'], path
        font = TTFont(args.cache/relative, recalcTimestamp=False)
        if 'fvar' in font:
            axes = {axis.axisTag:400 if axis.axisTag=='wght' else axis.defaultValue for axis in font['fvar'].axes}
            instantiateVariableFont(font, axes, inplace=True)
        coverage = set(font.getBestCmap())
        options = subset.Options()
        options.hinting = False
        options.layout_features = []
        options.drop_tables += ['GDEF','GSUB','GPOS','BASE','JSTF','STAT','DSIG','vhea','vmtx','VORG','MATH']
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=coverage)
        sub.subset(font)
        family = 'Vela Lyric '+key
        for nid, text in [(1,family),(2,'Regular'),(3,family+'-20261021'),(4,family+' Regular'),(6,'VelaLyric'+key+'-Regular')]:
            for platform, encoding, language in [(3,1,0x409),(1,0,0)]:
                font['name'].setName(text,nid,platform,encoding,language)
        font.recalcTimestamp = False
        filename = 'VelaLyric'+key+'-Regular.ttf'
        font.save(root/filename)
        result = TTFont(root/filename)
        assert set(result.getBestCmap()) == coverage
        assert 'glyf' in result and 'fvar' not in result
        data = (root/filename).read_bytes()
        checksum = 2166136261
        for byte in data:
            checksum = ((checksum^byte)*16777619)&0xffffffff
        license_name = key+'-OFL.txt'
        shutil.copyfile(args.cache/paths[1],root/license_name)
        records.append(dict(name=name,file=filename,bytes=len(data),fnv1a32=checksum,
            sha256=hashlib.sha256(data).hexdigest(),characters=len(coverage),license=license_name,
            source=lock['files'][relative]['url']))
        print(name,len(data),len(coverage),flush=True)
    (root/'manifest.json').write_text(json.dumps(records,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    header = ['/* SPDX-License-Identifier: Apache-2.0 */',
        '/* Generated by tools/prepare_lyric_fonts.py; do not edit. */','#pragma once',
        '#include <stdint.h>','#define GLASS_LYRIC_FACE_COUNT '+str(len(records)),
        'struct lyric_font_asset { const char *name,*file; uint32_t bytes,fnv; };',
        'static const struct lyric_font_asset lyric_font_assets[GLASS_LYRIC_FACE_COUNT]={']
    for record in records:
        header.append('  {"'+record['name']+'","'+record['file']+'",'+str(record['bytes'])+'u,UINT32_C('+str(record['fnv1a32'])+')},')
    header.append('};')
    args.header.write_text('\n'.join(header)+'\n',encoding='utf-8')
    archive = args.output/'lyric-fonts.zip'
    with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as out:
        for path in sorted(root.iterdir()):
            out.write(path,path.relative_to(args.output/'sdcard').as_posix())
    print('LYRIC_FONT_PACK_OK',archive,flush=True)

if __name__=='__main__':
    main()
