#!/usr/bin/env python3
"""Embed the ESPClaw computer CLI page without connection credentials."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
folder=root/'quickapp/claude_control'
source='// Generated by tools/generate_cli_resource.py; edit client.js and ui.js.\n'+(folder/'client.js').read_text(encoding='utf-8')+'\n'+(folder/'ui.js').read_text(encoding='utf-8')
(folder/'app.js').write_text(source,encoding='utf-8')
target = root / 'app/espdl-quickapp/overlay/apps/system/desktop/glass_cli_resource.inc'
target.write_text('/* Generated from quickapp/claude_control/app.js; contains no credentials. */\n'
                  'static const char glass_cli_source[] =\n' +
                  ''.join(json.dumps(line + '\n', ensure_ascii=True) + '\n' for line in source.splitlines()) + ';\n', encoding='utf-8')
