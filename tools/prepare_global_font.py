#!/usr/bin/env python3
"""Build one SD font for CJK, Hangul, Latin, Greek and Cyrillic (fonttools 4.60.1).

Only previously missing codepoints are added from each subsequent source. The
UI's Chinese Han forms keep priority. OpenType shaping tables are intentionally
not shipped to TinyTTF: this is not an Arabic/Indic shaping engine.
"""
import argparse,hashlib,json,shutil,tempfile,urllib.request
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset
from fontTools.merge import Merger

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cjk-dir',type=Path,required=True);p.add_argument('--extras-dir',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True);p.add_argument('--header',type=Path,required=True)
    p.add_argument('--fetch',action='store_true',help='Download missing pinned source fonts and licenses')
    a=p.parse_args();repo=Path(__file__).resolve().parents[1]
    lock=json.loads((repo/'app/espdl-quickapp/assets/music-fonts.lock.json').read_text())
    names=['notosanssc/NotoSansSC[wght].ttf','notosansjp/NotoSansJP[wght].ttf',
           'notosanskr/NotoSansKR[wght].ttf','notosans/NotoSans[wdth,wght].ttf']
    a.output.mkdir(parents=True,exist_ok=True);seen=set();sources=[];parts=[]
    with tempfile.TemporaryDirectory(prefix='vela-font-') as temp:
        for i,name in enumerate(names):
            root=a.cjk_dir if i<2 else a.extras_dir
            source=root/name;record=lock['files'][name]
            for relative in [name,name.split('/')[0]+'/OFL.txt']:
                cached=root/relative
                if a.fetch and not cached.exists():
                    cached.parent.mkdir(parents=True,exist_ok=True)
                    with urllib.request.urlopen(lock['files'][relative]['url'],timeout=90) as response:
                        data=response.read(32*1024*1024)
                    assert hashlib.sha256(data).hexdigest()==lock['files'][relative]['sha256']
                    cached.write_bytes(data)
            assert hashlib.sha256(source.read_bytes()).hexdigest()==record['sha256']
            license=source.parent/'OFL.txt';license_record=lock['files'][name.split('/')[0]+'/OFL.txt']
            assert hashlib.sha256(license.read_bytes()).hexdigest()==license_record['sha256']
            shutil.copyfile(license,a.output/(name.split('/')[0]+'-OFL.txt'))
            f=TTFont(source,recalcTimestamp=False)
            axes={axis.axisTag:(400 if axis.axisTag=='wght' else axis.defaultValue) for axis in f['fvar'].axes}
            instantiateVariableFont(f,axes,inplace=True)
            cmap=set(f.getBestCmap());wanted=cmap-seen;seen|=cmap
            sources.append({'file':name,'sha256':record['sha256'],'characters':len(cmap),'added':len(wanted)})
            if not wanted:continue
            options=subset.Options();options.hinting=False;options.layout_features=[]
            options.drop_tables+=['GDEF','GSUB','GPOS','BASE','JSTF','STAT','DSIG','vhea','vmtx','VORG','MATH']
            sub=subset.Subsetter(options=options);sub.populate(unicodes=wanted);sub.subset(f)
            f.recalcTimestamp=False;part=Path(temp)/(str(i)+'.ttf');f.save(part);parts.append(str(part))
        combined=Merger().merge(parts);combined.recalcTimestamp=False
        # Merged derivative uses its own family name and preserves all OFL files.
        for nid,value in [(1,'Vela Global'),(2,'Regular'),(3,'VelaGlobal-Regular-20261018'),
                          (4,'Vela Global Regular'),(6,'VelaGlobal-Regular')]:
            for platform,encoding,language in [(3,1,0x409),(1,0,0)]:combined['name'].setName(value,nid,platform,encoding,language)
        target=a.output/'VelaGlobal-Regular.ttf';combined.save(target)
    result=TTFont(target);coverage=set(result.getBestCmap());assert coverage==seen
    assert all(cp in coverage for cp in range(0xac00,0xd7a4))
    assert all(cp in coverage for cp in range(0x3041,0x3097))
    data=target.read_bytes();fnv=2166136261
    for byte in data:fnv=((fnv^byte)*16777619)&0xffffffff
    scripts={name:sum(cp in coverage for cp in range(lo,hi+1)) for name,lo,hi in
             [('hiragana',0x3041,0x3096),('katakana',0x30a1,0x30fa),('hangul_syllables',0xac00,0xd7a3),
              ('latin',0x20,0x24f),('greek',0x370,0x3ff),('cyrillic',0x400,0x52f)]}
    report={'file':target.name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),
            'fnv1a32':hex(fnv),'unicode_characters':len(coverage),'glyphs':result['maxp'].numGlyphs,
            'scripts':scripts,'sources':sources,'shaping_supported':False}
    (a.output/'manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    a.header.write_text('/* SPDX-License-Identifier: Apache-2.0; generated by prepare_global_font.py */\n'
        '#ifndef GLASS_SD_FONT_ASSET_H\n#define GLASS_SD_FONT_ASSET_H\n'
        '#define SD_FONT_DEFAULT_PATH "/sdcard/fonts/'+target.name+'"\n'
        '#define SD_FONT_BYTES '+str(len(data))+'u\n#define SD_FONT_FNV UINT32_C('+hex(fnv)+')\n'
        '#define SD_FONT_UNICODE '+str(len(coverage))+'u\n'
        '#define SD_FONT_SHA256 "'+report['sha256']+'"\n#endif\n')
    print(json.dumps(report))

if __name__=='__main__':main()
