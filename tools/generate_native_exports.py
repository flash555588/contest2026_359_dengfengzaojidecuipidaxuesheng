#!/usr/bin/env python3
"""Generate the firmware symbol table and host ABI for native modules.

Input:  app/espdl-quickapp/overlay/apps/system/desktop/native/exports.txt
Output: native_exports.c and native_host_abi.h next to it (do not edit them).

The host ABI digest covers the module ABI version and the exact exported
symbol set. A module built against another set is rejected before any of its
code runs. Use --check to verify that the generated files are current.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NATIVE = ROOT / 'app/espdl-quickapp/overlay/apps/system/desktop/native'
SYMBOL = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')


def module_abi(folder):
    text = (folder / 'native_module.h').read_text(encoding='utf-8')
    match = re.search(r'#define\s+OV_NATIVE_MODULE_ABI\s+(\d+)u', text)
    if not match:
        raise SystemExit('OV_NATIVE_MODULE_ABI not found in native_module.h')
    return int(match.group(1))


def read_symbols(path):
    names = []
    for number, raw in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        if not SYMBOL.fullmatch(line):
            raise SystemExit(f'{path}:{number}: invalid symbol {line!r}')
        names.append(line)
    if len(set(names)) != len(names):
        raise SystemExit(f'{path}: duplicate symbols')
    return sorted(names)


def render(names, abi):
    digest = hashlib.sha256(('ov-native-host\nabi=%d\n' % abi + '\n'.join(names) + '\n')
                            .encode()).hexdigest()
    lines = ['/* Generated by tools/generate_native_exports.py; do not edit. */',
             '#include <nuttx/symtab.h>']
    lines += [f'extern const char ov_import_{i}[] __asm__("{name}");' for i, name in enumerate(names)]
    lines.append('const struct symtab_s ov_native_exports[] = {')
    lines += [f'  {{"{name}", ov_import_{i}}},' for i, name in enumerate(names)]
    lines += ['};', f'const int ov_native_nexports = {len(names)};', '']
    header = ('/* Generated by tools/generate_native_exports.py; do not edit. */\n'
              '#ifndef OV_NATIVE_HOST_ABI_H\n#define OV_NATIVE_HOST_ABI_H\n'
              f'#define OV_NATIVE_HOST_ABI "{digest}"\n#endif\n')
    return '\n'.join(lines), header, digest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--native', type=Path, default=NATIVE)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    names = read_symbols(args.native / 'exports.txt')
    source, header, digest = render(names, module_abi(args.native))
    targets = {args.native / 'native_exports.c': source, args.native / 'native_host_abi.h': header}
    if args.check:
        stale = [str(p) for p, text in targets.items()
                 if not p.exists() or p.read_text(encoding='utf-8') != text]
        if stale:
            print('stale: ' + ', '.join(stale), file=sys.stderr)
            return 1
    else:
        for path, text in targets.items():
            path.write_text(text, encoding='utf-8', newline='\n')
    print(f'NATIVE_EXPORTS_OK symbols={len(names)} host_abi={digest}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
