#!/usr/bin/env python3
"""Package pinned Grok Ball and the native adapter into existing OuO entries."""
from pathlib import Path
import hashlib
import json
import re

repo=Path(__file__).resolve().parents[1]
base=repo/'ouo'
source=base/'vendor/grok-ball.js'
license=(base/'vendor/GROK-BALL-LICENSE.txt').read_text(encoding='utf-8')
engine=source.read_text(encoding='utf-8')
parts=[f'/* SPDX-License-Identifier: Apache-2.0 AND MIT\n{license}\n*/\n']
registry=re.findall(r"id: '([0-9]{2})', name: '([^']+)', group: '([^']+)'",engine)
assert len(registry)==32
parts += ['var GrokBall={EMOTIONS:'+json.dumps([dict(id=i,name=n,group=g) for i,n,g in registry],ensure_ascii=False)+'};']
parts += [(base/'grok_sd_adapter.js').read_text(encoding='utf-8'),(base/'grok_app.js').read_text(encoding='utf-8')]
app='\n'.join(parts)
desktop=repo/'app/espdl-quickapp/overlay/apps/system/desktop'
example=repo/'app/espdl-quickapp/overlay/apps/system/espclaw/qpk/ouo'
for path in [base/'app.js',desktop/'ouo/app.js',example/'app.js']:
    path.write_bytes(app.encode('utf-8'))
for path in [base/'manifest.json',example/'manifest.json']:
    manifest=json.loads(path.read_text(encoding='utf-8'))
    manifest['name']='Grok Ball';manifest['versionName']='2.0.0'
    if 'versionCode' in manifest:manifest['versionCode']=2
    path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
resource='/* Generated by tools/generate_grok_ouo.py. SPDX-License-Identifier: Apache-2.0 AND MIT */\nstatic const char g_ouo_app_js[] =\n'
resource+='\n'.join(json.dumps(line,ensure_ascii=False) for line in app.splitlines(keepends=True))+';\n'
resource+='const char *ouo_get_app_js(unsigned int *len) { *len=sizeof(g_ouo_app_js)-1; return g_ouo_app_js; }\n'
for path in [base/'ouo_resource.c',desktop/'ouo_resource.c']:path.write_bytes(resource.encode('utf-8'))
catalog=example.parent/'catalog.json'
data=json.loads(catalog.read_text(encoding='utf-8'))
for entry in data['examples']:
    if entry['id']=='ouo':
        entry.update(name='Grok Ball 表情',source_sha256=hashlib.sha256(app.encode()).hexdigest(),
            purpose='SD 原始像素帧播放：32 种表情、九方向注视、自旋彩带、滑动切换与 AI emotionId。',
            verification='素材由固定版本 SDK 离线生成；固件不运行 SVG。实板结果见对应烧录报告。')
catalog.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
# Refresh the same references compiled into ESPClaw, preserving its guide and
# other examples. This also prevents old board evidence from describing Grok.
assets=desktop/'glass_qpk_assets.inc'
embedded=assets.read_text(encoding='utf-8')
embedded=embedded.replace('原内置入口使用全屏尺寸；借用动画时按当前内容区重新布局。状态名如“聆听”“充电”只是表情',
    'Grok Ball 2.0.0 使用上游状态 ID（00..07、10..21、30..41），不沿用旧 OuO 含义；按 ui.getSize() 内容区布局')
for symbol,path in [('qpk_example_catalog',catalog),('qpk_asset_6',example/'manifest.json'),
                    ('qpk_asset_7',example/'app.js'),('qpk_asset_8',example/'README.md')]:
    content=path.read_text(encoding='utf-8')
    replacement='static const char '+symbol+'[] =\n'
    replacement+='\n'.join(json.dumps(line,ensure_ascii=False) for line in content.splitlines(keepends=True))+';'
    pattern=r'static const char '+symbol+r'\[\] =\n.*?;(?=\nstatic const)'
    embedded,count=re.subn(pattern,lambda match:replacement,embedded,flags=re.S)
    assert count==1,symbol
assets.write_bytes(embedded.encode('utf-8'))
print('GROK_PACKAGE_OK',len(app.encode()),'bytes')
