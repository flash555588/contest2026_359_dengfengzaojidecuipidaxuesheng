#!/usr/bin/env python3
"""Compile small camera toolbar tiles shared by LVGL and RGB565 composition.

Keep the reference geometry and plain red shutter. Outline controls and captions
are rasterized at build time, without a runtime decoder or extra framebuffer.
"""
from pathlib import Path
from PIL import Image, ImageFont, ImageDraw
import argparse
import math

args=argparse.ArgumentParser()
args.add_argument('--font',type=Path,default=Path('C:/Windows/Fonts/arial.ttf'))
args=args.parse_args()

desktop = Path(__file__).resolve().parents[1] / 'app/espdl-quickapp/overlay/apps/system/desktop'
image = Image.open(desktop / 'camera/reference.jpg').convert('RGB')
assert image.size == (863, 1920)
# Name, original atlas rectangle, landscape placement, keep original text upright.
tiles = [
    ('filter', (730, 1328, 820, 1418), (708, 40, 48, 48), False),
    ('shutter', (346, 1588, 516, 1758), (842, 250, 100, 100), False),
    ('gallery', (38, 1616, 134, 1724), (864, 514, 56, 56), False),
    ('record', (586, 1630, 674, 1718), (866, 128, 50, 50), False),
    ('switch', (734, 1630, 818, 1718), (866, 36, 50, 50), False),
    ('mode', None, (836, 182, 112, 22), True),
    ('style', None, (700, 94, 64, 18), True),
]
lines = ['/* Generated by tools/generate_camera_reference.py. */',
         '#pragma once', '#include <stdint.h>',
         'struct camera_reference_tile { int x,y,w,h; const uint16_t *pixels; };']
count = 0
# Code-native outline symbols for the newly assigned recording/camera actions.
def action_icon(name,color):
 im=Image.new('RGB',(200,200),0);d=ImageDraw.Draw(im)
 d.rounded_rectangle((3,3,196,196),radius=56,fill=(20,22,25),
                     outline=(43,46,51),width=3)
 line=lambda points:d.line([(x*4,y*4) for x,y in points],fill=color,width=7,joint='curve')
 if name=='filter':
  for cx,cy in [(100,70),(74,116),(126,116)]:
   d.ellipse((cx-29,cy-29,cx+29,cy+29),outline=color,width=7)
 elif name=='gallery':
  d.rounded_rectangle((40,40,160,160),radius=22,outline=color,width=7)
  d.ellipse((66,64,86,84),fill=color)
  line([(11,35),(23,23),(29,29),(34,24),(39,30)])
 elif name=='record':
  d.rounded_rectangle((32,64,128,136),radius=12,outline=color,width=7)
  line([(33,21),(43,16),(43,34),(33,29)])
 else:
  d.rounded_rectangle((48,68,156,140),radius=10,outline=color,width=7)
  d.ellipse((80,80,120,120),outline=color,width=7)
  line([(8,17),(10,11),(17,7),(29,6),(38,12),(31,10)])
  line([(38,12),(37,5)])
  line([(42,33),(40,39),(33,43),(21,44),(12,38),(19,40)])
  line([(12,38),(13,45)])
 return im.resize((50,50),Image.Resampling.LANCZOS)
icons={name:action_icon(name,(245,245,247)) for name in ['record','switch','filter','gallery']}
caption_font=ImageFont.truetype(str(args.font),13)
def mode_label(video):
    icon=Image.new('RGB',(112,22),0)
    ImageDraw.Draw(icon).text((56,11),'VIDEO' if video else 'PHOTO',
                             font=caption_font,fill=(239,56,41) if video else (170,170,176),anchor='mm')
    return icon
def style_label(style):
    icon=Image.new('RGB',(64,18),0)
    ImageDraw.Draw(icon).text((32,9),['STD','VIVID','B&W','WARM','COOL','FILM'][style],
                             font=caption_font,fill=(155,160,168),anchor='mm')
    return icon
for name, rect, (x, y, w, h), upright in tiles:
    if rect is not None:left,top,right,bottom=rect
    icon=icons[name].resize((w,h),Image.Resampling.LANCZOS) if name in icons else None
    if name=='mode':icon=mode_label(False)
    if name=='style':icon=style_label(0)
    values = []
    for dy in range(h):
        for dx in range(w):
            if icon is not None:r,g,b=icon.getpixel((dx,dy))
            elif upright:
                sx = left + (dx + .5) * (right - left) / w
                sy = top + (dy + .5) * (bottom - top) / h
            else:
                sx = right - (dy + .5) * (right - left) / h
                sy = top + (dx + .5) * (bottom - top) / w
            if icon is None:
                r, g, b = image.getpixel((min(right-1,int(sx)), min(bottom-1,int(sy))))
            if name == 'shutter':
                # User override: a clean red shutter, with no mascot or icon.
                coverage=max(0.0,min(1.0,48-math.hypot(dx-49.5,dy-49.5)))
                r,g,b=(round(c*coverage) for c in (239,56,41))
            values.append((r >> 3) << 11 | (g >> 2) << 5 | b >> 3)
    lines.append(f'static const uint16_t camera_ref_{name}[{len(values)}] = {{')
    for i in range(0, len(values), 16):
        lines.append('  ' + ','.join(f'0x{n:04x}' for n in values[i:i+16]) + ',')
    lines.append('};')
    count += len(values) * 2
lines.append('static const struct camera_reference_tile camera_reference_tiles[] = {')
for name, _, (x, y, w, h), _ in tiles:
    lines.append(f'  {{{x},{y},{w},{h},camera_ref_{name}}},')
lines += ['};', f'#define CAMERA_REFERENCE_TILE_COUNT {len(tiles)}',
          f'#define CAMERA_REFERENCE_SHUTTER_TILE {[t[0] for t in tiles].index("shutter")}',
          f'#define CAMERA_REFERENCE_FILTER_TILE {[t[0] for t in tiles].index("filter")}',
          f'#define CAMERA_REFERENCE_RECORD_TILE {[t[0] for t in tiles].index("record")}',
          f'#define CAMERA_REFERENCE_MODE_TILE {[t[0] for t in tiles].index("mode")}',
          f'#define CAMERA_REFERENCE_STYLE_TILE {[t[0] for t in tiles].index("style")}']
# Selected recording and style indicators use the same scene positions.
active=action_icon('record',(239,56,41));values=[]
for y in range(50):
 for x in range(50):
  r,g,b=active.getpixel((x,y));values.append((r>>3)<<11|(g>>2)<<5|b>>3)
lines.append('static const uint16_t camera_record_active[2500] = {')
for i in range(0,len(values),16):lines.append('  '+','.join(f'0x{n:04x}' for n in values[i:i+16])+',')
lines.append('};');count+=5000
values=[]
video_label=mode_label(True)
for y in range(22):
 for x in range(112):
  r,g,b=video_label.getpixel((x,y));values.append((r>>3)<<11|(g>>2)<<5|b>>3)
lines.append('static const uint16_t camera_mode_video[2464] = {')
for i in range(0,len(values),16):lines.append('  '+','.join(f'0x{n:04x}' for n in values[i:i+16])+',')
lines.append('};');count+=len(values)*2
for style,color in [(1,(239,120,42)),(2,(235,235,235)),(3,(235,167,104)),(4,(120,174,220)),(5,(194,168,125))]:
 values=[]
 active_filter=action_icon('filter',color).resize((48,48),Image.Resampling.LANCZOS)
 for y in range(48):
  for x in range(48):
   r,g,b=active_filter.getpixel((x,y))
   if (x-24)**2+(y-43)**2<=4:r,g,b=color
   values.append((r>>3)<<11|(g>>2)<<5|b>>3)
 lines.append(f'static const uint16_t camera_filter_{style}[2304] = {{')
 for i in range(0,len(values),16):lines.append('  '+','.join(f'0x{n:04x}' for n in values[i:i+16])+',')
 lines.append('};');count+=4608
 values=[]
 caption=style_label(style)
 for y in range(18):
  for x in range(64):
   r,g,b=caption.getpixel((x,y));values.append((r>>3)<<11|(g>>2)<<5|b>>3)
 lines.append(f'static const uint16_t camera_style_{style}[1152] = {{')
 for i in range(0,len(values),16):lines.append('  '+','.join(f'0x{n:04x}' for n in values[i:i+16])+',')
 lines.append('};');count+=len(values)*2
# Anti-aliased type is rasterized once at build time, shared by both displays.
font=ImageFont.truetype(str(args.font),19)
for active in range(2):
 for index,text in enumerate(['1×','1.5×','2×','3×']):
  mask=font.getmask(text,mode='L');mw,mh=mask.size
  ox=(48-mw)//2;oy=(48-mh)//2
  data=[]
  for y in range(48):
   for x in range(48):
    distance=math.hypot(x-23.5,y-23.5)
    edge=max(0.0,min(1.0,24-distance)) if active else 0
    base=0xe84a3d if distance>22.5 else 0x24272c
    background=sum(round(((base>>shift)&255)*edge)<<shift for shift in [16,8,0])
    coverage=mask[(y-oy)*mw+x-ox] if 0<=x-ox<mw and 0<=y-oy<mh else 0
    foreground=0xf5f5f7 if active else 0x9499a1
    rgb=[]
    for shift in [16,8,0]:
     bg=(background>>shift)&255;fg=(foreground>>shift)&255
     rgb.append((bg*(255-coverage)+fg*coverage)//255)
    r,g,b=rgb;data.append((r>>3)<<11|(g>>2)<<5|(b>>3))
  lines.append(f'static const uint16_t camera_zoom_{active}_{index}[2304] = {{')
  for i in range(0,len(data),16):lines.append('  '+','.join(f'0x{n:04x}' for n in data[i:i+16])+',')
  lines.append('};');count+=len(data)*2
lines.append('static const uint16_t *const camera_reference_zoom_pixels[2][4] = {')
for active in range(2):lines.append('  {'+','.join(f'camera_zoom_{active}_{index}' for index in range(4))+'},')
lines.append('};')
(desktop / 'camera_reference_pixels.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
print('CAMERA_REFERENCE_TILES_OK', count, 'bytes in read-only sprite data')
