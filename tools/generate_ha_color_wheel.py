"""Generate one flash-resident RGB565+A8 HSV disc; no per-frame raster work."""
from pathlib import Path
import colorsys,math
side=160;pixels=bytearray();alpha=bytearray()
for y in range(side):
    for x in range(side):
        dx=(x+.5-side/2)/(side/2-1);dy=(y+.5-side/2)/(side/2-1)
        radius=math.hypot(dx,dy)
        hue=((math.atan2(dy,dx)*180/math.pi+90)/360)%1
        r,g,b=(round(c*255) for c in colorsys.hsv_to_rgb(hue,min(1,radius),1))
        value=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        pixels.extend((value&255,value>>8));alpha.append(round(max(0,min(1,(1-radius)*(side/2-1)+.5))*255))
data=pixels+alpha
target=Path(__file__).resolve().parents[1]/'app/espdl-quickapp/overlay/apps/system/desktop/ha_color_wheel.inc'
target.write_text('/* SPDX-License-Identifier: Apache-2.0 */\n/* Generated by tools/generate_ha_color_wheel.py, HSV hue clockwise from top. */\nstatic const uint8_t qpk_color_wheel_pixels[] = {\n'+''.join('  '+','.join('0x%02x'%v for v in data[i:i+24])+',\n' for i in range(0,len(data),24))+'};\n',encoding='utf-8')
print('HA_COLOR_WHEEL_ASSET_OK',side,len(data))
