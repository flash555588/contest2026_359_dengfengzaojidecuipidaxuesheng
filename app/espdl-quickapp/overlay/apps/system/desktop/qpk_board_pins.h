#pragma once
#include <nuttx/config.h>
/* Factory P4X J1: GPIO0/1 are NC while the 32 kHz crystal is fitted.
 * Display, C6, audio, storage and USB pins remain owned by their services. */
#define QPK_HEADER_GPIO_MASK 0x7cu
#ifndef CONFIG_ESPRESSIF_I2C1_SDAPIN
#define CONFIG_ESPRESSIF_I2C1_SDAPIN 2
#define CONFIG_ESPRESSIF_I2C1_SCLPIN 3
#endif
#ifndef CONFIG_ESPRESSIF_SPI2_CSPIN
#define CONFIG_ESPRESSIF_SPI2_CSPIN 6
#define CONFIG_ESPRESSIF_SPI2_CLKPIN 3
#define CONFIG_ESPRESSIF_SPI2_MOSIPIN 4
#define CONFIG_ESPRESSIF_SPI2_MISOPIN 5
#endif
#ifndef CONFIG_ESPRESSIF_UART1_TXPIN
#define CONFIG_ESPRESSIF_UART1_TXPIN 4
#define CONFIG_ESPRESSIF_UART1_RXPIN 5
#endif
#ifndef CONFIG_ESPRESSIF_LEDC_CHANNEL0_PIN
#define CONFIG_ESPRESSIF_LEDC_CHANNEL0_PIN 2
#define CONFIG_ESPRESSIF_LEDC_CHANNEL1_PIN 3
#define CONFIG_ESPRESSIF_LEDC_CHANNEL2_PIN 4
#define CONFIG_ESPRESSIF_LEDC_CHANNEL3_PIN 6
#endif
/* Out-of-range routes yield a forbidden bit, avoiding undefined shifts. */
#define QPK_PIN_MASK(pin) ((unsigned)(pin)<7 ? (1u << ((unsigned)(pin)&31)) : 1u)
#define QPK_I2C_MASK (QPK_PIN_MASK(CONFIG_ESPRESSIF_I2C1_SDAPIN)|QPK_PIN_MASK(CONFIG_ESPRESSIF_I2C1_SCLPIN))
#define QPK_SPI_MASK (QPK_PIN_MASK(CONFIG_ESPRESSIF_SPI2_CSPIN)|QPK_PIN_MASK(CONFIG_ESPRESSIF_SPI2_CLKPIN)|QPK_PIN_MASK(CONFIG_ESPRESSIF_SPI2_MOSIPIN)|QPK_PIN_MASK(CONFIG_ESPRESSIF_SPI2_MISOPIN))
#define QPK_UART_MASK (QPK_PIN_MASK(CONFIG_ESPRESSIF_UART1_TXPIN)|QPK_PIN_MASK(CONFIG_ESPRESSIF_UART1_RXPIN))
